// ─── Filled nav icons (reicon) ────────────────────────────────────────
// The sidebar's navigational rows use reicon's Filled weight for stronger
// presence against the 12px labels. Same call shape as every other wrapper;
// `strokeWidth` is meaningless on filled glyphs and is dropped.

function makeFilledIcon(ReiconBase: ReiconComponent): IconType {
	const Icon = ({ size, className, color, style }: IconProps) => (
		<ReiconBase
			weight="Filled"
			size={size}
			className={className}
			color={typeof color === "string" ? color : undefined}
			style={style}
		/>
	);
	return Icon;
}

