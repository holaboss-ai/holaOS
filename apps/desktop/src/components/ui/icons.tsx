/**
 * App-wide icon set, drawn from `@hugeicons/core-free-icons` and
 * rendered through `<HugeiconsIcon>`. Wrappers are exported under
 * the matching `lucide-react` names so feature code can swap
 * `from "@/components/ui/icons"` for `from "@/components/ui/icons"` with
 * no JSX changes.
 */

type IconProps = Omit<HugeiconsIconProps, "icon">;

// Mirror lucide's `LucideIcon` shorthand so existing slots typed as
// `LucideIcon` can rename the import to `IconType` and stay valid.
export type IconType = (props: IconProps) => ReactElement;

// Hugeicons' default `strokeWidth` is 1.5 — slightly anemic next to
// our Tailwind borders / status dots. 1.75 lines icons up with text
// labels without tipping into "too bold". The sidebar rebinds at 2.
const DEFAULT_STROKE_WIDTH = 1.75;

function makeIcon(icon: IconSvgElement): IconType {
	const Icon = ({ strokeWidth, ...rest }: IconProps) => (
		<HugeiconsIcon
			icon={icon}
			strokeWidth={strokeWidth ?? DEFAULT_STROKE_WIDTH}
			{...rest}
		/>
	);
	return Icon;
}

